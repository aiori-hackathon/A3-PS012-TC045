def remap(ip, sandbox):
    """10.10.a.b -> 127.10.a.b in sandbox mode so the lab can run on loopback."""
    return ("127.10." + ip.split(".", 2)[2]) if sandbox and ip.startswith("10.10.") else ip


SOFTWARE_FOR = {"authoritative_only": {"bind", "nsd"}, "liar_local_answer": {"dnsmasq"}, "wildcard_hijacker": {"dnsmasq"}, "ra_refuser": {"bind"}, "sinkhole_rewriter": {"bind"}}
DEFAULT_SOFTWARE = {"bind", "unbound", "dnsmasq"}


def load(path, attach=False):
    data = yaml.safe_load(Path(path).read_text())
    lab, targets = data["lab"], data["targets"]
    net = ipaddress.ip_network(lab["subnet"])
    ids, ips = set(), {lab["canary"]["ip"], lab["clients"]["external"]["ip"], lab["clients"]["control"]["ip"]}
    if len(targets) > MAX_TARGETS:
        sys.exit(f"error: {len(targets)} targets, maximum is {MAX_TARGETS}")
    by_id = {t["id"]: t for t in targets}
    for t in targets:
        if t["id"] in ids or t["ip"] in ips:
            sys.exit(f"error: duplicate id or ip for {t['id']}")
        ids.add(t["id"]); ips.add(t["ip"])
        if ipaddress.ip_address(t["ip"]) not in net:
            sys.exit(f"error: {t['id']} ip outside {lab['subnet']}")
        if t["behavior"] not in BEHAVIOR_EXPECTED:
            sys.exit(f"error: {t['id']} unknown behavior {t['behavior']}")
        if t["expected"] != BEHAVIOR_EXPECTED[t["behavior"]]:
            sys.exit(f"error: {t['id']} expected label {t['expected']} does not match behavior {t['behavior']}")
        if t["software"] not in SOFTWARE_FOR.get(t["behavior"], DEFAULT_SOFTWARE):
            sys.exit(f"error: {t['id']} software {t['software']} cannot be {t['behavior']}")
        if t["behavior"] == "forwarder":
            ok = t.get("forward_to") in by_id or (t.get("forward_to_ip") and ipaddress.ip_address(t["forward_to_ip"]) in net)
            if not ok:
                sys.exit(f"error: {t['id']} forward_to must name another target (or forward_to_ip an address in the lab)")
    return lab, targets, by_id


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--targets", default="lab/targets.yaml")
    ap.add_argument("--out", default="lab/generated")
    ap.add_argument("--sandbox", action="store_true", help="remap 10.10.x.y to 127.10.x.y and use per-target run dirs")
    ap.add_argument("--attach", action="store_true", help="challenge profile: join the existing lab network, no canary or clients")
    ap.add_argument("--project", default=None, help="Docker Compose project name (default rl, or rlc with --attach)")
    ap.add_argument("--run-root", default="/tmp/rl-run", help="sandbox only: where per-target var dirs live")
    a = ap.parse_args()
    lab, targets, by_id = load(a.targets, a.attach)
    sb = a.sandbox
    env = Environment(undefined=StrictUndefined, trim_blocks=True, lstrip_blocks=True, keep_trailing_newline=True)
    out = Path(a.out)
    if out.exists():
        shutil.rmtree(out)
    (out / "targets").mkdir(parents=True)
    (out / "canary").mkdir()
    cz, bz = lab["canary"]["zone"], lab["baseline_zone"]
    canary_ip = remap(lab["canary"]["ip"], sb)
    trusted = remap(lab["trusted_range"], sb) if not sb else "127.10." + lab["trusted_range"].split(".", 2)[2]
    common = dict(canary_zone=cz, canary_ip=canary_ip, baseline_zone=bz, trusted=trusted)

    def paths(sub):
        if sb:
            base = Path(a.run_root) / sub
            return dict(conf=str(out.resolve() / ("canary" if sub == "canary" else f"targets/{sub}")),
                        vardir=str(base / "var"), logdir=str(base / "log"))
        return dict(conf="/etc/rl", vardir="/var/lib/rl", logdir="/var/log/named")

    # canary server
    p = paths("canary")
    (out / "canary" / "named.conf").write_text(env.from_string(CANARY_CONF).render(ip=canary_ip, **common, **p))
    (out / "canary" / "canary.zone").write_text(env.from_string(CANARY_ZONE).render(ip=canary_ip, marker_ip=lab["canary"]["marker_ip"], **common))

    for t in targets:
        d = out / "targets" / t["id"]
        d.mkdir()
        ip, sw, bh = remap(t["ip"], sb), t["software"], t["behavior"]
        ctx = dict(ip=ip, **common, **paths(t["id"]))
        fwd = None
        if bh == "forwarder":
            fwd = remap(by_id[t["forward_to"]]["ip"] if t.get("forward_to") in by_id else t["forward_to_ip"], sb)
        if bh in ("broken_upstream", "sinkhole_rewriter"):
            fwd = remap("10.10.0.250", sb)
        if sw == "bind":
            mode = {"authoritative_only": "authoritative", "policy_refusing": "policy", "ra_refuser": "ra_refuser"}.get(bh, "open")
            sink = bh == "sinkhole_rewriter"
            if sink:
                (d / "rpz.zone").write_text(env.from_string(RPZ_ZONE).render(marker_ip=lab["canary"]["marker_ip"], **ctx))
            c = env.from_string(BIND_CONF).render(mode=mode, sinkhole=sink, forwarders=[fwd] if fwd else [],
                                                stub=(mode != "authoritative" and not fwd), auth_zone=(mode == "authoritative"), **ctx)
            (d / "named.conf").write_text(c)
        elif sw == "unbound":
            (d / "unbound.conf").write_text(env.from_string(UNBOUND_CONF).render(policy=(bh == "policy_refusing"), forward_to=fwd, **ctx))
        elif sw == "dnsmasq":
            liar = {"liar_local_answer": "zone", "wildcard_hijacker": "wildcard"}.get(bh, "")
            (d / "dnsmasq.conf").write_text(env.from_string(DNSMASQ_CONF).render(
                forward_to=fwd, liar=liar, marker_ip=lab["canary"]["marker_ip"], dead_ip=remap("10.10.0.250", sb), **ctx))
        elif sw == "nsd":
            (d / "nsd.conf").write_text(env.from_string(NSD_CONF).render(**ctx))
        if bh == "authoritative_only":
            (d / "baseline.zone").write_text(env.from_string(BASELINE_ZONE).render(**ctx))

    ext = dict(lab["clients"]["external"]); ctl = dict(lab["clients"]["control"])
    ext["role"], ctl["role"] = "external-probe-client", "control-client"
    tlist = [dict(t, impair=IMPAIR.get(t["behavior"], "none"), delay_ms=DELAY_MS.get(t["behavior"], 3000)) for t in targets]
    (out / "docker-compose.yml").write_text(env.from_string(COMPOSE).render(
        network=lab["network"], subnet=lab["subnet"], canary=lab["canary"], targets=tlist, ext=ext, clients=[ext, ctl],
        attach=a.attach, project=a.project or ("rlc" if a.attach else "rl")))
    print(f"generated {len(targets)} targets + canary in {out}/ (sandbox={sb})")


if __name__ == "__main__":
    main()
